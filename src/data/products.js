// all block "hotlinking" — loading their images from a different domain.
// They return a 403 or an empty response, which is why the <img> shows grey.
//
// ─── THE FIX ──────────────────────────────────────────────────────────────────
// We route every image through wsrv.nl — a free, fast, open-source image proxy
// (https://wsrv.nl) that fetches the image server-side, bypassing hotlink blocks.
// Usage:  https://wsrv.nl/?url=<original_url>&w=400&h=300&fit=cover&output=webp
//
// For brands whose CDN still blocks proxies, we use their official website's
// open-graph / press-kit images, which are always publicly accessible.
// ─────────────────────────────────────────────────────────────────────────────

// Helper: wrap any URL with the wsrv.nl proxy
